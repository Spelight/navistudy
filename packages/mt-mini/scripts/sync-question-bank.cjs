const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const source = path.resolve(root, '..', 'military-theory-quiz', 'src', 'data', 'question-bank.json');
const target = path.resolve(root, 'miniprogram', 'data', 'question-bank.js');
const bank = JSON.parse(fs.readFileSync(source, 'utf8'));

if (!Array.isArray(bank.questions) || !Array.isArray(bank.chapters)) {
  throw new Error('题库格式无效：缺少 questions 或 chapters');
}

const output = `// Generated by scripts/sync-question-bank.cjs. Do not edit manually.\nmodule.exports = ${JSON.stringify(bank, null, 2)};\n`;
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output, 'utf8');
console.log(`Synced ${bank.questions.length} questions to ${target}`);

